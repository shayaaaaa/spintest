const comp = (base, token, path, init = {}) => fetch(base.replace(/\/+$/, '') + path, { ...init, headers: { ...(init.headers || {}), Authorization: 'Bearer ' + token } });
export async function companionHealth(base, token) {
  if (!/^https:/i.test(base) && !/^http:\/\/(localhost|127\.0\.0\.1)/i.test(base)) throw new Error('Use an https:// address (a tunnel such as cloudflared, Tailscale Funnel or ngrok): the browser blocks plain http from an https app.');
  const r = await comp(base, token, '/health');
  if (r.status === 401) throw new Error('The companion rejected the token.');
  if (!r.ok) throw new Error(`Companion error ${r.status}`);
  return r.json();
}
export async function companionStart(base, token, files) {
  const fd = new FormData();
  for (const f of files) fd.append('files', new Blob([f.data]), f.path);
  const r = await comp(base, token, '/jobs', { method: 'POST', body: fd });
  if (!r.ok) throw new Error(`Companion refused the job: ${r.status} ${await r.text()}`);
  return r.json();
}
