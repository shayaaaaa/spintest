const HF = 'https://huggingface.co';
const hfHeaders = () => { const t = getSecret('hf_token'); if (!t) throw new Error('Add a Hugging Face token (write access) in Settings → Keys first.'); return { Authorization: 'Bearer ' + t }; };

export async function hfJobStart(cfg, files, { flavor = 'a10g-small', timeout = '6h', onProgress } = {}) {
  const { whoami, createRepo, uploadFiles } = await import('../models/hf.js');
  const me = await whoami();
  const ns = me.name;
  const slug = (cfg.name || 'ai-agent-run').replace(/[^\w.-]+/g, '-').slice(0, 60);
  const dataRepo = `${ns}/${slug}-data`, outRepo = `${ns}/${slug}`;
  onProgress?.('Uploading dataset to a private HF dataset repo…');
  await createRepo(dataRepo, { type: 'dataset', private: true });
  await uploadFiles(dataRepo, files, { type: 'dataset', message: 'Ai Agent offload job' });
  onProgress?.('Starting the job…');
  const script = files.find(f => f.path === 'train.py').data;
  const spec = {
    dockerImage: 'ghcr.io/astral-sh/uv:python3.12-bookworm',
    command: ['bash', '-c', `echo ${b64(script)} | base64 -d > /tmp/train.py && uv run /tmp/train.py`],
    arguments: [], flavor,
    environment: { DATA_REPO: dataRepo, OUTPUT_REPO: outRepo, OUTPUT_DIR: '/tmp/outputs', PYTHONUNBUFFERED: '1' },
    secrets: { HF_TOKEN: getSecret('hf_token') },
    timeoutSeconds: parseTimeout(timeout),
    labels: { name: slug, app: 'ai-agent' },
  };
  const r = await fetch(`${HF}/api/jobs/${ns}`, { method: 'POST', headers: { ...hfHeaders(), 'Content-Type': 'application/json' }, body: JSON.stringify(spec) });
  if (!r.ok) throw new Error(`HF Jobs refused the job (${r.status}): ${(await r.text()).slice(0, 300)}. Jobs need a PRO or Team/Enterprise account with billing.`);
  const job = await r.json();
  return { ns, id: job.id || job._id || job.metadata?.id, dataRepo, outRepo, flavor };
}
const parseTimeout = (t) => { const m = /^(\d+(?:\.\d+)?)([smhd]?)$/.exec(String(t)); if (!m) return 21600; return Math.round(+m[1] * ({ s: 1, m: 60, h: 3600, d: 86400 }[m[2]] || 1)); };

export async function hfJobStatus(ns, id) {
  const r = await fetch(`${HF}/api/jobs/${ns}/${id}`, { headers: hfHeaders() });
  if (!r.ok) throw new Error(`HF Jobs status ${r.status}`);
  const j = await r.json();
  return { stage: j.status?.stage || 'UNKNOWN', message: j.status?.message || '', raw: j };
}
export async function hfJobCancel(ns, id) { await fetch(`${HF}/api/jobs/${ns}/${id}/cancel`, { method: 'POST', headers: hfHeaders() }); }

// Streams job logs (server-sent events). onLine(text). Resolves when the stream ends or signal aborts.
export async function hfJobLogs(ns, id, onLine, signal) {
  const r = await fetch(`${HF}/api/jobs/${ns}/${id}/logs`, { headers: { ...hfHeaders(), Accept: 'text/event-stream' }, signal });
  if (!r.ok || !r.body) return;
  const reader = r.body.pipeThrough(new TextDecoderStream()).getReader();
  let buf = '';
  for (;;) {
    const { value, done } = await reader.read();
    if (done) break;
    buf += value;
    let i;
    while ((i = buf.indexOf('\n')) >= 0) {
      const line = buf.slice(0, i).trimEnd(); buf = buf.slice(i + 1);
      if (!line.startsWith('data:')) continue;
      const payload = line.slice(5).trim();
      try { const d = JSON.parse(payload); onLine(d.data ?? d.message ?? payload); } catch { onLine(payload); }
    }
  }
}

