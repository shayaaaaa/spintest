export function colabNotebook(cfg, files) {
  const md = (s) => ({ cell_type: 'markdown', metadata: {}, source: s.split('\n').map((l, i, a) => l + (i < a.length - 1 ? '\n' : '')) });
  const code = (s) => ({ cell_type: 'code', metadata: {}, execution_count: null, outputs: [], source: s.split('\n').map((l, i, a) => l + (i < a.length - 1 ? '\n' : '')) });
  const cells = [
    md(`# ${cfg.name || 'Ai Agent training'}\n\n${(cfg.method || 'sft').toUpperCase()} (${cfg.tuning || 'lora'}) of **${cfg.base || 'a new model'}**, generated by Ai Agent Studio.\n\n1. Runtime → Change runtime type → **T4 GPU** (or better).\n2. Runtime → **Run all**.\n3. Download the GGUF at the end (or set an HF token to push it to your account), then import it in Ai Agent → Studio → Models.`),
    code('%%capture\n!pip install unsloth trl datasets hf_transfer'),
  ];
  for (const f of files.filter(f => f.path !== 'train.py')) cells.push(code(`# ${f.path}\nimport base64\nopen(${JSON.stringify(f.path)}, "wb").write(base64.b64decode(${JSON.stringify(b64(f.data))}))`));
  cells.push(code(`%%writefile train.py\n${files.find(f => f.path === 'train.py').data}`));
  cells.push(md('Optional: push the results to your Hugging Face account. Put a **write** token in Colab secrets as `HF_TOKEN`, then set `OUTPUT_REPO` below.'));
  cells.push(code(`import os\nos.environ["DATA_DIR"] = "."\n# os.environ["OUTPUT_REPO"] = "your-username/${(cfg.name || 'ai-agent-model').replace(/[^\w.-]+/g, '-')}"\ntry:\n    from google.colab import userdata\n    os.environ["HF_TOKEN"] = userdata.get("HF_TOKEN")\nexcept Exception:\n    pass\n%run train.py`));
  cells.push(code('import glob\nfrom google.colab import files\nfor f in glob.glob("outputs/gguf/*.gguf"):\n    print("Downloading", f)\n    files.download(f)'));
  return JSON.stringify({ nbformat: 4, nbformat_minor: 0, metadata: { colab: { provenance: [], gpuType: 'T4' }, accelerator: 'GPU', kernelspec: { name: 'python3', display_name: 'Python 3' }, language_info: { name: 'python' } }, cells }, null, 1);
}
function b64(s) { const u8 = typeof s === 'string' ? new TextEncoder().encode(s) : new Uint8Array(s); let out = ''; for (let i = 0; i < u8.length; i += 0x8000) out += String.fromCharCode.apply(null, u8.subarray(i, i + 0x8000)); return btoa(out); }

