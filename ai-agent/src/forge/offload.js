const py = (v) => JSON.stringify(v).replace(/\btrue\b/g, 'True').replace(/\bfalse\b/g, 'False').replace(/\bnull\b/g, 'None');

// cfg: {base, method: sft|pretrain|scratch|dpo|grpo, tuning: lora|qlora|full, epochs, maxSteps, lr, batch, gradAccum, seqLen,
//       rank, alpha, targets, beta, group, maxNew, reward, completionOnly, gguf, name, scratch: {...llama config}}
export function trainScript(cfg) {
  const C = {
    base: cfg.base || null, method: cfg.method || 'sft', tuning: cfg.method === 'scratch' ? 'full' : (cfg.tuning || 'lora'),
    epochs: cfg.epochs ?? 1, max_steps: cfg.maxSteps || -1, lr: cfg.lr || (cfg.tuning === 'full' ? 2e-5 : cfg.method === 'scratch' ? 1e-3 : 2e-4),
    batch: cfg.batch || 2, grad_accum: cfg.gradAccum || 4, seq_len: cfg.seqLen || 2048, rank: cfg.rank || 16, alpha: cfg.alpha || 2 * (cfg.rank || 16),
    targets: (cfg.targets || ['q', 'k', 'v', 'o', 'gate', 'up', 'down']).map(t => t + '_proj'), beta: cfg.beta ?? (cfg.method === 'dpo' ? 0.1 : 0.04),
    group: cfg.group || 8, max_new: cfg.maxNew || 512, reward: cfg.reward || 'exact', completion_only: cfg.completionOnly !== false,
    gguf: cfg.gguf || 'q4_k_m', name: cfg.name || 'ai-agent-model', scratch: cfg.scratch || null, seed: 3407,
  };
  return `# /// script
# requires-python = ">=3.10"
# dependencies = ["unsloth", "trl", "datasets", "huggingface_hub", "hf_transfer"]
# ///
"""Generated by Ai Agent Studio: ${C.method.toUpperCase()} (${C.tuning}) on ${C.base || 'a new model'}.

Runs anywhere with an NVIDIA GPU: Google Colab, Hugging Face Jobs, RunPod, Modal, or your own PC.
Reads data.jsonl (+ validation.jsonl) from DATA_DIR (default: this folder) or from the HF dataset DATA_REPO.
Writes outputs/lora, outputs/merged and outputs/gguf; pushes them to OUTPUT_REPO when set (needs HF_TOKEN).
"""
import os, re, json, math, glob
os.environ.setdefault("HF_HUB_ENABLE_HF_TRANSFER", "1")
CONFIG = ${py(C)}

DATA_DIR = os.environ.get("DATA_DIR", os.path.dirname(os.path.abspath(__file__)))
if os.environ.get("DATA_REPO"):
    from huggingface_hub import snapshot_download
    DATA_DIR = snapshot_download(os.environ["DATA_REPO"], repo_type="dataset", token=os.environ.get("HF_TOKEN"))
OUT = os.environ.get("OUTPUT_DIR", "outputs")
os.makedirs(OUT, exist_ok=True)
method, tuning = CONFIG["method"], CONFIG["tuning"]
print(f"[ai-agent] {method} / {tuning} on {CONFIG['base']}", flush=True)

def read_jsonl(name):
    p = os.path.join(DATA_DIR, name)
    if not os.path.exists(p): return []
    with open(p, encoding="utf-8") as f: return [json.loads(l) for l in f if l.strip()]

def to_messages(r):
    if isinstance(r.get("messages"), list): return [{"role": m["role"], "content": str(m.get("content", ""))} for m in r["messages"]]
    if isinstance(r.get("conversations"), list):
        roles = {"human": "user", "gpt": "assistant"}
        return [{"role": roles.get(m.get("from"), m.get("from", "user")), "content": m.get("value", "")} for m in r["conversations"]]
    if "instruction" in r and "output" in r:
        u = r["instruction"] + ("\\n\\n" + r["input"] if r.get("input") else "")
        return [{"role": "user", "content": u}, {"role": "assistant", "content": r["output"]}]
    if "prompt" in r and ("completion" in r or "response" in r):
        return [{"role": "user", "content": r["prompt"]}, {"role": "assistant", "content": r.get("completion", r.get("response"))}]
    return None

train_rows, val_rows = read_jsonl("data.jsonl"), read_jsonl("validation.jsonl")
print(f"[ai-agent] {len(train_rows)} training rows, {len(val_rows)} validation rows", flush=True)
from datasets import Dataset
import torch
bf16 = torch.cuda.is_available() and torch.cuda.is_bf16_supported()

if method == "scratch":
    from transformers import LlamaConfig, LlamaForCausalLM, PreTrainedTokenizerFast
    tok_dir = DATA_DIR if os.path.exists(os.path.join(DATA_DIR, "tokenizer.json")) else None
    tokenizer = PreTrainedTokenizerFast.from_pretrained(tok_dir) if tok_dir else None
    if tokenizer is None: raise SystemExit("Training from scratch needs tokenizer.json next to the data (export it from Ai Agent).")
    model = LlamaForCausalLM(LlamaConfig(**CONFIG["scratch"]))
    if tokenizer.pad_token is None: tokenizer.pad_token = tokenizer.eos_token
else:
    from unsloth import FastLanguageModel
    model, tokenizer = FastLanguageModel.from_pretrained(model_name=CONFIG["base"], max_seq_length=CONFIG["seq_len"],
        load_in_4bit=(tuning == "qlora"), full_finetuning=(tuning == "full"), token=os.environ.get("HF_TOKEN"))
    if tuning != "full":
        model = FastLanguageModel.get_peft_model(model, r=CONFIG["rank"], lora_alpha=CONFIG["alpha"], target_modules=CONFIG["targets"],
            lora_dropout=0, bias="none", use_gradient_checkpointing="unsloth", random_state=CONFIG["seed"])

def chat_text(msgs, gen=False):
    return tokenizer.apply_chat_template(msgs, tokenize=False, add_generation_prompt=gen)

common = dict(per_device_train_batch_size=CONFIG["batch"], gradient_accumulation_steps=CONFIG["grad_accum"], num_train_epochs=CONFIG["epochs"],
    max_steps=CONFIG["max_steps"], learning_rate=CONFIG["lr"], warmup_ratio=0.05, lr_scheduler_type="cosine", logging_steps=1,
    weight_decay=0.01 if tuning == "full" else 0.0, bf16=bf16, fp16=not bf16, output_dir=os.path.join(OUT, "checkpoints"),
    save_steps=200, save_total_limit=2, report_to="none", seed=CONFIG["seed"], optim="adamw_8bit" if method != "scratch" else "adamw_torch")

def make_config(cls, **kw):
    # TRL renamed max_seq_length -> max_length; accept both.
    try: return cls(**kw)
    except TypeError:
        if "max_length" in kw: kw["max_seq_length"] = kw.pop("max_length")
        return cls(**kw)

def make_trainer(cls, **kw):
    try: return cls(processing_class=tokenizer, **kw)
    except TypeError: return cls(tokenizer=tokenizer, **kw)

if method in ("sft", "pretrain", "scratch"):
    from trl import SFTTrainer, SFTConfig
    def rows_to_text(rows):
        out = []
        for r in rows:
            m = to_messages(r)
            out.append({"text": chat_text(m) if m else (r.get("text", "") + (tokenizer.eos_token or ""))})
        return Dataset.from_list(out)
    train_ds, val_ds = rows_to_text(train_rows), (rows_to_text(val_rows) if val_rows else None)
    args = make_config(SFTConfig, dataset_text_field="text", max_length=CONFIG["seq_len"], packing=(method != "sft"),
        eval_strategy="steps" if val_ds is not None else "no", eval_steps=50, **common)
    trainer = make_trainer(SFTTrainer, model=model, train_dataset=train_ds, eval_dataset=val_ds, args=args)
    if method == "sft" and CONFIG["completion_only"]:
        tpl = tokenizer.chat_template or ""
        parts = None
        if "<|im_start|>" in tpl: parts = ("<|im_start|>user\\n", "<|im_start|>assistant\\n")
        elif "<|start_header_id|>" in tpl: parts = ("<|start_header_id|>user<|end_header_id|>\\n\\n", "<|start_header_id|>assistant<|end_header_id|>\\n\\n")
        elif "<start_of_turn>" in tpl: parts = ("<start_of_turn>user\\n", "<start_of_turn>model\\n")
        if parts:
            from unsloth.chat_templates import train_on_responses_only
            trainer = train_on_responses_only(trainer, instruction_part=parts[0], response_part=parts[1])
elif method == "dpo":
    from trl import DPOTrainer, DPOConfig
    def dpo_row(r):
        p = r["prompt"] if isinstance(r["prompt"], list) else [{"role": "user", "content": r["prompt"]}]
        return {"prompt": chat_text(p, gen=True), "chosen": str(r["chosen"]) + (tokenizer.eos_token or ""), "rejected": str(r["rejected"]) + (tokenizer.eos_token or "")}
    train_ds = Dataset.from_list([dpo_row(r) for r in train_rows])
    args = make_config(DPOConfig, beta=CONFIG["beta"], max_length=CONFIG["seq_len"], max_prompt_length=CONFIG["seq_len"] // 2, **common)
    trainer = make_trainer(DPOTrainer, model=model, ref_model=None, train_dataset=train_ds, args=args)
elif method == "grpo":
    from trl import GRPOTrainer, GRPOConfig
    def strip_think(s): return re.sub(r"<think>[\\s\\S]*?</think>", "", s).strip()
    def final_answer(s):
        t = strip_think(s)
        m = re.findall(r"\\\\boxed\\{([^{}]*)\\}", t) or re.findall(r"(?:final answer|answer)\\s*[:：]\\s*(.+)", t, re.I) or re.findall(r"####\\s*(.+)", t)
        return (m[-1] if m else (t.strip().splitlines() or [""])[-1]).strip()
    def num(s):
        m = re.findall(r"-?\\d+(?:\\.\\d+)?", str(s).replace(",", ""))
        return float(m[-1]) if m else None
    def norm(s): return re.sub(r"\\s+", " ", str(s).lower()).strip().rstrip(".")
    BUILTIN = {
        "exact": lambda c, a: float(norm(final_answer(c)) == norm(a)),
        "contains": lambda c, a: float(norm(a) in norm(strip_think(c))),
        "numeric": lambda c, a: float(num(final_answer(c)) is not None and num(a) is not None and abs(num(final_answer(c)) - num(a)) < 1e-6),
        "regex": lambda c, a: float(re.search(str(a), strip_think(c), re.I) is not None),
        "format": lambda c, a: float(re.match(r"^\\s*<think>[\\s\\S]+?</think>\\s*\\S", c) is not None),
        "json": lambda c, a: float(_is_json(strip_think(c))),
        "length": lambda c, a: max(0.0, 1 - abs(len(strip_think(c).split()) - 100) / 100),
    }
    BUILTIN["math"] = lambda c, a: BUILTIN["numeric"](c, a) + 0.2 * float(bool(re.search(r"(\\\\boxed\\{|answer\\s*[:：]|####)", strip_think(c), re.I)))
    def _is_json(t):
        try: json.loads(t.strip().strip("\`").removeprefix("json")); return True
        except Exception: return False
    names = [n.strip() for n in str(CONFIG["reward"]).split("+") if n.strip() in BUILTIN] or ["contains"]
    def reward_fn(prompts, completions, answer=None, **kw):
        out = []
        for i, c in enumerate(completions):
            text = c[-1]["content"] if isinstance(c, list) else str(c)
            a = answer[i] if answer is not None else ""
            out.append(sum(BUILTIN[n](text, a) for n in names))
        return out
    train_ds = Dataset.from_list([{"prompt": [{"role": "user", "content": r.get("prompt") or r.get("question")}], "answer": str(r.get("answer", ""))} for r in train_rows])
    args = make_config(GRPOConfig, num_generations=CONFIG["group"], max_completion_length=CONFIG["max_new"], max_prompt_length=CONFIG["seq_len"] // 2, beta=CONFIG["beta"],
        **{**common, "per_device_train_batch_size": max(CONFIG["batch"], CONFIG["group"])})
    trainer = make_trainer(GRPOTrainer, model=model, reward_funcs=[reward_fn], train_dataset=train_ds, args=args)
else:
    raise SystemExit(f"Unknown method {method}")

stats = trainer.train()
print(f"[ai-agent] training done: {stats}", flush=True)

# ---- save ----
if method != "scratch" and tuning != "full":
    model.save_pretrained(os.path.join(OUT, "lora")); tokenizer.save_pretrained(os.path.join(OUT, "lora"))
    print("[ai-agent] saved LoRA adapter", flush=True)
if method == "scratch":
    model.save_pretrained(os.path.join(OUT, "merged")); tokenizer.save_pretrained(os.path.join(OUT, "merged"))
else:
    try: model.save_pretrained_merged(os.path.join(OUT, "merged"), tokenizer, save_method="merged_16bit")
    except Exception as e: print(f"[ai-agent] merged save failed: {e}", flush=True)
    try:
        model.save_pretrained_gguf(os.path.join(OUT, "gguf"), tokenizer, quantization_method=CONFIG["gguf"])
        print("[ai-agent] saved GGUF", flush=True)
    except Exception as e: print(f"[ai-agent] GGUF export failed: {e}", flush=True)
# Unsloth may write GGUFs next to the folder; gather them.
os.makedirs(os.path.join(OUT, "gguf"), exist_ok=True)
for f in glob.glob("*.gguf") + glob.glob(os.path.join(OUT, "*.gguf")) + glob.glob(os.path.join(OUT, "gguf*", "**", "*.gguf"), recursive=True):
    dst = os.path.join(OUT, "gguf", os.path.basename(f))
    if os.path.abspath(f) != os.path.abspath(dst): os.replace(f, dst)

if os.environ.get("OUTPUT_REPO"):
    from huggingface_hub import create_repo, upload_folder
    repo = os.environ["OUTPUT_REPO"]
    create_repo(repo, private=True, exist_ok=True, token=os.environ.get("HF_TOKEN"))
    for sub in ("gguf", "lora", "merged"):
        p = os.path.join(OUT, sub)
        if os.path.isdir(p) and os.listdir(p):
            upload_folder(repo_id=repo, folder_path=p, path_in_repo=sub, token=os.environ.get("HF_TOKEN"), commit_message=f"Ai Agent: {sub}")
    print(f"[ai-agent] pushed outputs to https://huggingface.co/{repo}", flush=True)
print("AI_AGENT_DONE", flush=True)
`;
}

// Files that travel with every offload: train.py, data, optional tokenizer (scratch) and a config record.
export async function bundleFiles(cfg, { dataset, tokenizerDir } = {}) {
  const dsDir = `/datasets/${dataset}`;
  const files = [{ path: 'train.py', data: trainScript(cfg) }];
  files.push({ path: 'data.jsonl', data: await vfs.readText(`${dsDir}/data.jsonl`) });
  const val = await vfs.readText(`${dsDir}/validation.jsonl`).catch(() => null);
  if (val) files.push({ path: 'validation.jsonl', data: val });
  if (tokenizerDir) for (const f of ['tokenizer.json', 'tokenizer_config.json']) { const t = await vfs.readText(`${tokenizerDir}/${f}`).catch(() => null); if (t) files.push({ path: f, data: t }); }
  files.push({ path: 'ai-agent-config.json', data: JSON.stringify({ ...cfg, dataset, created: new Date().toISOString() }, null, 2) });
  return files;
}

