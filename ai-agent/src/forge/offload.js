// Downloads a GGUF from the companion into the Hub as a ready-to-chat model.
export async function companionImportGGUF(base, token, id, file, name, onProgress) {
  const r = await comp(base, token, `/jobs/${id}/files/${file.path.split('/').map(encodeURIComponent).join('/')}`);
  if (!r.ok || !r.body) throw new Error(`Download failed: ${r.status}`);
  const safe = name.replace(/[^\w.-]+/g, '-');
  const dir = `/models/llm/${safe}`;
  const fname = file.path.split('/').pop();
  const ws = await vfs.createWriteStream(`${dir}/${fname}`);
  const reader = r.body.getReader();
  let got = 0;
  for (;;) { const { value, done } = await reader.read(); if (done) break; await ws.write(value); got += value.byteLength; onProgress?.(got / (file.size || got)); }
  await ws.close();
  await vfs.writeJSON(`${dir}/manifest.json`, { id: safe, name, kind: 'llm', engine: 'gguf', gguf: { files: [fname] }, bytes: got, context: 4096, source: { offload: 'companion', job: id }, added: Date.now(), status: 'ready' });
  const { refreshModels } = await import('../models/registry.js');
  await refreshModels();
  return dir;
}

