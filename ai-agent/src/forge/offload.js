export async function loadOffloadJobs() {
  const jobs = [];
  for (const e of await vfs.list(DIR).catch(() => [])) if (e.name.endsWith('.json')) { const j = await vfs.readJSON(e.path, null); if (j) jobs.push(j); }
  jobs.sort((a, b) => b.created - a.created);
  offloadStore.set({ jobs });
  return jobs;
}
export async function saveOffloadJob(job) {
  job.id ||= uid('off-'); job.created ||= Date.now(); job.updated = Date.now();
  await vfs.writeJSON(`${DIR}/${job.id}.json`, job);
  offloadStore.set(s => ({ jobs: [job, ...s.jobs.filter(j => j.id !== job.id)] }));
  return job;
}
