export function fileIcon(name, kind) {
  if (kind === 'directory') return 'folder';
  const e = (name.split('.').pop() || '').toLowerCase();
  if (['png', 'jpg', 'jpeg', 'gif', 'webp', 'svg', 'heic', 'bmp'].includes(e)) return 'image';
  if (['js', 'mjs', 'ts', 'tsx', 'jsx', 'py', 'html', 'css', 'json', 'c', 'cpp', 'h', 'rs', 'go', 'java', 'swift', 'kt', 'sh', 'rb', 'php', 'sql', 'yaml', 'yml', 'toml', 'xml'].includes(e)) return 'fileCode';
  if (['md', 'txt', 'pdf', 'docx', 'rtf'].includes(e)) return 'fileText';
  if (['csv', 'xlsx', 'jsonl', 'tsv'].includes(e)) return 'table';
  if (['pptx', 'key'].includes(e)) return 'presentation';
  if (['mp3', 'wav', 'm4a', 'ogg', 'flac'].includes(e)) return 'music';
  if (['mp4', 'mov', 'webm', 'mkv'].includes(e)) return 'video';
  if (['gguf', 'safetensors', 'onnx', 'bin', 'pt', 'wasm'].includes(e)) return 'cpu';
  if (['zip', 'gz', 'tar', 'tgz'].includes(e)) return 'package';
  return 'file';
}
